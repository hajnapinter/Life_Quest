-- Life Quest database schema
-- Run this script in the Supabase SQL editor.

create table public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    display_name text not null,
    location text,
    selected_categories text[] not null default '{}',
    points integer not null default 0 check (points >= 0),
    created_at timestamptz not null default now()
);

create table public.challenges (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null,
    category text not null,
    points integer not null check (points > 0),
    is_active boolean not null default true
);

create table public.completed_challenges (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    challenge_id bigint not null references public.challenges(id) on delete cascade,
    completed_on date not null default current_date,
    created_at timestamptz not null default now(),
    unique (user_id, challenge_id)
);

create table public.squads (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(name) between 2 and 50),
    invite_code text not null unique,
    created_by uuid not null references public.profiles(id) on delete cascade,
    created_at timestamptz not null default now()
);

create table public.squad_members (
    squad_id bigint not null references public.squads(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    joined_at timestamptz not null default now(),
    primary key (squad_id, user_id)
);

alter table public.profiles enable row level security;
alter table public.challenges enable row level security;
alter table public.completed_challenges enable row level security;
alter table public.squads enable row level security;
alter table public.squad_members enable row level security;

create policy "Users can view their own profile"
on public.profiles for select
using (auth.uid() = id);

create policy "Users can create their own profile"
on public.profiles for insert
with check (auth.uid() = id);

create policy "Users can update their own profile"
on public.profiles for update
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "Authenticated users can view active challenges"
on public.challenges for select
using (auth.role() = 'authenticated' and is_active = true);

create policy "Users can view their completed challenges"
on public.completed_challenges for select
using (auth.uid() = user_id);

create policy "Users can complete challenges for themselves"
on public.completed_challenges for insert
with check (auth.uid() = user_id);

create policy "Users can view squads they belong to"
on public.squads for select
using (
    created_by = auth.uid()
    or exists (
        select 1 from public.squad_members
        where squad_members.squad_id = squads.id
        and squad_members.user_id = auth.uid()
    )
);

create policy "Authenticated users can create squads"
on public.squads for insert
with check (auth.uid() = created_by);

create policy "Users can view their squad memberships"
on public.squad_members for select
using (auth.uid() = user_id);

create policy "Users can join squads as themselves"
on public.squad_members for insert
with check (auth.uid() = user_id);

create or replace function public.complete_challenge(challenge_id_input bigint)
returns table (new_points integer)
language plpgsql
security definer
set search_path = public
as $$
declare
    current_user_id uuid := auth.uid();
    challenge_points integer;
    updated_points integer;
begin
    if current_user_id is null then
        raise exception 'Authentication required';
    end if;

    select points into challenge_points
    from public.challenges
    where id = challenge_id_input and is_active = true;

    if challenge_points is null then
        raise exception 'Challenge not found';
    end if;

    if exists (
        select 1 from public.completed_challenges
        where user_id = current_user_id and challenge_id = challenge_id_input
    ) then
        raise exception 'Challenge already completed';
    end if;

    insert into public.completed_challenges (user_id, challenge_id)
    values (current_user_id, challenge_id_input);

    update public.profiles
    set points = points + challenge_points
    where id = current_user_id
    returning points into updated_points;

    return query select updated_points;
end;
$$;

grant execute on function public.complete_challenge(bigint) to authenticated;

create or replace function public.get_weekly_leaderboard()
returns table (
    display_name text,
    weekly_points bigint,
    quests_completed bigint
)
language sql
stable
security definer
set search_path = public
as $$
    select
        p.display_name,
        sum(c.points)::bigint as weekly_points,
        count(cc.id)::bigint as quests_completed
    from public.completed_challenges cc
    join public.profiles p on p.id = cc.user_id
    join public.challenges c on c.id = cc.challenge_id
    where cc.completed_on >= date_trunc('week', current_date)::date
    group by p.id, p.display_name
    order by weekly_points desc, quests_completed desc, p.display_name asc
    limit 50;
$$;

grant execute on function public.get_weekly_leaderboard() to authenticated;

create or replace function public.create_squad(squad_name_input text)
returns table (squad_id bigint, invite_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
    current_user_id uuid := auth.uid();
    new_squad_id bigint;
    new_invite_code text;
begin
    if current_user_id is null then
        raise exception 'Authentication required';
    end if;
    if char_length(trim(squad_name_input)) < 2 then
        raise exception 'Squad name is too short';
    end if;

    new_invite_code := upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
    insert into public.squads (name, invite_code, created_by)
    values (trim(squad_name_input), new_invite_code, current_user_id)
    returning id, squads.invite_code into new_squad_id, new_invite_code;

    insert into public.squad_members (squad_id, user_id)
    values (new_squad_id, current_user_id);

    return query select new_squad_id, new_invite_code;
end;
$$;

create or replace function public.join_squad(invite_code_input text)
returns table (squad_id bigint, squad_name text)
language plpgsql
security definer
set search_path = public
as $$
declare
    current_user_id uuid := auth.uid();
    selected_squad_id bigint;
    selected_squad_name text;
begin
    if current_user_id is null then
        raise exception 'Authentication required';
    end if;

    select id, name into selected_squad_id, selected_squad_name
    from public.squads
    where invite_code = upper(trim(invite_code_input));

    if selected_squad_id is null then
        raise exception 'Squad not found';
    end if;

    insert into public.squad_members (squad_id, user_id)
    values (selected_squad_id, current_user_id)
    on conflict do nothing;

    return query select selected_squad_id, selected_squad_name;
end;
$$;

create or replace function public.get_my_squad()
returns table (
    squad_id bigint,
    squad_name text,
    invite_code text,
    display_name text,
    member_points integer
)
language sql
stable
security definer
set search_path = public
as $$
    select
        s.id,
        s.name,
        s.invite_code,
        p.display_name,
        p.points
    from public.squads s
    join public.squad_members own_members on own_members.squad_id = s.id
    join public.squad_members members on members.squad_id = s.id
    join public.profiles p on p.id = members.user_id
    where own_members.user_id = auth.uid()
    order by p.points desc, p.display_name asc;
$$;

grant execute on function public.create_squad(text) to authenticated;
grant execute on function public.join_squad(text) to authenticated;
grant execute on function public.get_my_squad() to authenticated;

